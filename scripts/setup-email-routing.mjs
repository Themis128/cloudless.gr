#!/usr/bin/env node
/**
 * Configure Cloudflare Email Routing programmatically using the Cloudflare API.
 * 
 * This script:
 * 1. Enables Email Routing on the zone
 * 2. Sets up MX records
 * 3. Configures SPF records
 * 4. Adds DKIM records (provided by Cloudflare)
 * 5. Creates destination address and routing rules
 */

import { config } from 'dotenv';
config();

const CF_API_TOKEN = process.env.CLOUDFLARE_API_TOKEN;
const DOMAIN = 'cloudless.gr';
const DESTINATION_EMAIL = process.env.DESTINATION_EMAIL || 'tbaltzakis@cloudless.gr';

if (!CF_API_TOKEN) {
  console.error('ERROR: CLOUDFLARE_API_TOKEN not set');
  process.exit(1);
}

const API_BASE = 'https://api.cloudflare.com/client/v4';

async function api(path, options = {}) {
  const response = await fetch(`${API_BASE}${path}`, {
    ...options,
    headers: {
      'Authorization': `Bearer ${CF_API_TOKEN}`,
      'Content-Type': 'application/json',
      'Accept': 'application/json',
      ...options.headers,
    },
  });
  const data = await response.json();
  if (!response.ok) {
    console.error(`API Error: ${response.status}`, data);
    throw new Error(`API request failed: ${response.status}`);
  }
  return data;
}

async function main() {
  console.log('🔧 Configuring Cloudflare Email Routing...\n');

  // Get zone ID
  console.log(`[1/6] Looking up zone for ${DOMAIN}...`);
  const zone = await api(`/zones?name=${DOMAIN}`);
  if (!zone.result?.length) {
    console.error(`Zone not found for ${DOMAIN}`);
    process.exit(1);
  }
  const ZONE_ID = zone.result[0].id;
  const ACCOUNT_ID = zone.result[0].account.id;
  console.log(`   Zone ID: ${ZONE_ID}`);

  // Step 1: Enable Email Routing on the zone
  console.log('\n[2/6] Enabling Email Routing...');
  try {
    await api(`/zones/${ZONE_ID}/email/routing/setup`, { method: 'POST', body: '{}' });
    console.log('   ✓ Email Routing enabled');
  } catch (e) {
    if (e.message.includes('already')) {
      console.log('   Email Routing already enabled');
    } else {
      throw e;
    }
  }

  // Step 2: Get or create destination address
  console.log(`\n[3/6] Setting up destination address (${DESTINATION_EMAIL})...`);
  try {
    const addresses = await api(`/accounts/${ACCOUNT_ID}/email/routing/addresses`);
    const existingDest = addresses.result?.find(a => a.email === DESTINATION_EMAIL);
    
    if (existingDest) {
      console.log('   ✓ Destination exists');
    } else {
      const result = await api(`/accounts/${ACCOUNT_ID}/email/routing/addresses`, {
        method: 'POST',
        body: JSON.stringify({ email: DESTINATION_EMAIL }),
      });
      console.log('   ✓ Destination created (requires verification)');
      console.log(`   Verification needed - check email: ${DESTINATION_EMAIL}`);
    }
  } catch (e) {
    // May fail if already exists with different verification state
    console.log('   Destination may already exist or requires verification');
  }

  // Step 3: Configure MX records for Email Routing
  console.log('\n[4/6] Configuring MX records...');
  const mxRecords = [
    { type: 'MX', name: DOMAIN, content: 'mx1.mail.protonmail.ch', priority: 10, ttl: 3600 },
    { type: 'MX', name: DOMAIN, content: 'mx2.mail.protonmail.ch', priority: 20, ttl: 3600 },
  ];

  for (const record of mxRecords) {
    try {
      // Check if MX record exists
      const existing = await api(`/zones/${ZONE_ID}/dns_records?type=MX&name=${DOMAIN}&content=${record.content}`);
      if (!existing.result?.length) {
        await api(`/zones/${ZONE_ID}/dns_records`, {
          method: 'POST',
          body: JSON.stringify(record),
        });
        console.log(`   ✓ Added MX: ${record.content}`);
      } else {
        console.log(`   MX already exists: ${record.content}`);
      }
    } catch (e) {
      console.log(`   Note: Could not add MX record (${record.content})`);
    }
  }

  // Step 4: Configure SPF record
  console.log('\n[5/6] Adding SPF record...');
  try {
    const spfRecord = await api(`/zones/${ZONE_ID}/dns_records?type=TXT&name=${DOMAIN}`);
    const hasSPF = spfRecord.result?.some(r => r.content?.includes('cloudflare.net'));
    
    if (!hasSPF) {
      await api(`/zones/${ZONE_ID}/dns_records`, {
        method: 'POST',
        body: JSON.stringify({
          type: 'TXT',
          name: DOMAIN,
          content: 'v=spf1 include:cloudflare.net ~all',
          ttl: 3600,
          proxied: false,
        }),
      });
      console.log('   ✓ SPF record added: v=spf1 include:cloudflare.net ~all');
    } else {
      console.log('   SPF record already exists');
    }
  } catch (e) {
    console.log('   Note: Could not add SPF record');
  }

  // Step 5: Get DKIM records (provided by Cloudflare Email Routing)
  console.log('\n[6/6] Checking DKIM records (auto-generated by Email Routing)...');
  try {
    const dkim = await api(`/zones/${ZONE_ID}/email/routing/dns_records`);
    console.log('   DKIM records:', JSON.stringify(dkim.result || [], null, 2));
    
    // DKIM records are automatically provided - create them if not present
    for (const record of (dkim.result || [])) {
      const exists = await api(`/zones/${ZONE_ID}/dns_records?type=${record.type}&name=${record.name}`);
      if (!exists.result?.length) {
        await api(`/zones/${ZONE_ID}/dns_records`, {
          method: 'POST',
          body: JSON.stringify({
            type: record.type,
            name: record.name,
            content: record.content,
            ttl: 3600,
            proxied: false,
          }),
        });
        console.log(`   ✓ Added ${record.type} record: ${record.name}`);
      }
    }
  } catch (e) {
    console.log('   Note: Could not check/create DKIM records');
  }

  // Step 6: Create routing rule for noreply@cloudless.gr
  console.log(`\n[7/6] Creating routing rule for noreply@${DOMAIN}...`);
  try {
    const rules = await api(`/accounts/${ACCOUNT_ID}/email/routing/rules`);
    const hasRule = rules.result?.some(r => r.pattern === `noreply@${DOMAIN}`);
    
    if (!hasRule) {
      await api(`/accounts/${ACCOUNT_ID}/email/routing/rules`, {
        method: 'POST',
        body: JSON.stringify({
          name: 'noreply',
          enabled: true,
          pattern: `noreply@${DOMAIN}`,
          actions: [{ type: 'forward', value: DESTINATION_EMAIL }],
        }),
      });
      console.log(`   ✓ Routing rule created: noreply@${DOMAIN} → ${DESTINATION_EMAIL}`);
    } else {
      console.log(`   Routing rule already exists: noreply@${DOMAIN}`);
    }
  } catch (e) {
    console.log('   Note: Could not create routing rule (may need manual verification)');
  }

  console.log('\n✅ Email Routing Configuration Complete!');
  console.log('\nNext steps:');
  console.log('1. Verify the destination address (check email inbox)');
  console.log('2. Deploy the worker with EMAIL binding: pnpm cf:deploy:free');
  console.log('3. Test email sending from the worker');
}

main().catch(console.error);