#!/usr/bin/env python3
"""Build a court-ready video-evidence index PDF for a case dossier folder.

Scans a case directory for *.mp4 clips (typically under video-*/ dirs), pairs
each clip with its contact-strip image (<name>_strip.jpg), computes SHA-256,
probes duration with ffprobe when available, and renders a PDF index with
embedded thumbnails, hashes, and full file paths.

Usage:
    python build_video_index.py <case_dir> [--out VIDEO-INDEX.pdf]
                                [--title "..."] [--per-page 6]

Requires: reportlab (pip install reportlab). ffprobe optional.
"""

import argparse
import hashlib
import shutil
import subprocess
import sys
from datetime import datetime
from pathlib import Path

VIDEO_EXTS = {".mp4", ".mov", ".mkv", ".avi"}


def sha256(path: Path, chunk: int = 1 << 20) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for b in iter(lambda: f.read(chunk), b""):
            h.update(b)
    return h.hexdigest()


def _cv2_duration(path: Path) -> float | None:
    try:
        import cv2

        cap = cv2.VideoCapture(str(path))
        if not cap.isOpened():
            return None
        fps = cap.get(cv2.CAP_PROP_FPS) or 0
        frames = cap.get(cv2.CAP_PROP_FRAME_COUNT) or 0
        cap.release()
        return frames / fps if fps > 0 else None
    except Exception:
        return None


def probe_duration(path: Path) -> float | None:
    ffprobe = shutil.which("ffprobe")
    if ffprobe:
        try:
            out = subprocess.run(
                [
                    ffprobe,
                    "-v",
                    "quiet",
                    "-print_format",
                    "json",
                    "-show_format",
                    str(path),
                ],
                capture_output=True,
                text=True,
                timeout=30,
            )
            import json

            return float(json.loads(out.stdout)["format"]["duration"])
        except Exception:
            pass
    return _cv2_duration(path)


def find_clips(case_dir: Path) -> list[Path]:
    clips = []
    for p in sorted(case_dir.rglob("*")):
        if p.is_file() and p.suffix.lower() in VIDEO_EXTS:
            # skip inside archives/zips dirs if any
            clips.append(p)
    return clips


def strip_for(clip: Path) -> Path | None:
    for cand in (
        clip.with_name(clip.stem + "_strip.jpg"),
        clip.with_name(clip.stem + "_strip.png"),
    ):
        if cand.exists():
            return cand
    return None


def fmt_dur(sec: float | None) -> str:
    if sec is None:
        return "-"
    m, s = divmod(int(sec), 60)
    h, m = divmod(m, 60)
    return f"{h}:{m:02d}:{s:02d}" if h else f"{m:02d}:{s:02d}"


def build_pdf(clips: list[dict], case_dir: Path, out: Path, title: str, per_page: int) -> None:
    from reportlab.lib import colors
    from reportlab.lib.enums import TA_CENTER
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
    from reportlab.lib.units import mm
    from reportlab.platypus import (
        Image,
        PageBreak,
        Paragraph,
        SimpleDocTemplate,
        Spacer,
        Table,
        TableStyle,
    )

    styles = getSampleStyleSheet()
    h1 = ParagraphStyle(
        "h1c", parent=styles["Title"], alignment=TA_CENTER, fontSize=14, spaceAfter=6
    )
    small = ParagraphStyle(
        "small",
        parent=styles["Normal"],
        fontSize=7,
        leading=9,
        textColor=colors.HexColor("#444444"),
    )

    doc = SimpleDocTemplate(
        str(out),
        pagesize=A4,
        leftMargin=15 * mm,
        rightMargin=15 * mm,
        topMargin=15 * mm,
        bottomMargin=15 * mm,
        title=title,
    )
    story = [
        Paragraph(title, h1),
        Paragraph(
            f"Case folder: {case_dir}<br/>"
            f"Clips indexed: {len(clips)} — generated by "
            "build_video_index.py",
            small,
        ),
        Spacer(1, 6),
    ]

    img_w, img_h = 55 * mm, 31 * mm  # 16:9-ish
    rows_per = max(1, per_page)
    idx = 0
    while idx < len(clips):
        batch = clips[idx : idx + rows_per]
        data = []
        for c in batch:
            cells = []
            strip = c["strip"]
            if strip and strip.exists():
                try:
                    img = Image(str(strip), width=img_w, height=img_h)
                    img.hAlign = "LEFT"
                    cells.append(img)
                except Exception:
                    cells.append(Paragraph("(no preview)", small))
            else:
                cells.append(Paragraph("(no contact strip)", small))
            dup = c.get("dup_of")
            meta = [
                Paragraph(
                    f"<b>{c['rel']}</b>"
                    + (f" <font color='red'>(duplicate of {dup})</font>" if dup else ""),
                    small,
                ),
                Paragraph(f"SHA-256: {c['sha']}", small),
                Paragraph(
                    f"Size: {c['size_mb']:.1f} MB &nbsp; Duration: {fmt_dur(c['dur'])}", small
                ),
                Paragraph(f"Modified: {c['mtime']}", small),
            ]
            cells.append(meta)
            data.append(cells)
        t = Table(data, colWidths=[img_w + 4 * mm, doc.width - img_w - 4 * mm])
        t.setStyle(
            TableStyle(
                [
                    ("VALIGN", (0, 0), (-1, -1), "TOP"),
                    ("LEFTPADDING", (0, 0), (-1, -1), 0),
                    ("RIGHTPADDING", (0, 0), (-1, -1), 0),
                    ("TOPPADDING", (0, 0), (-1, -1), 4),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
                    ("LINEBELOW", (0, 0), (-1, -1), 0.25, colors.HexColor("#cccccc")),
                ]
            )
        )
        story.append(t)
        story.append(Spacer(1, 4))
        idx += rows_per
        if idx < len(clips):
            story.append(PageBreak())
    doc.build(story)


def main() -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("case_dir", type=Path)
    ap.add_argument("--out", type=Path, default=None)
    ap.add_argument("--title", default=None)
    ap.add_argument("--per-page", type=int, default=4)
    args = ap.parse_args()

    case_dir = args.case_dir.resolve()
    if not case_dir.is_dir():
        print(f"error: not a directory: {case_dir}", file=sys.stderr)
        return 2

    clips = []
    for p in find_clips(case_dir):
        rel = p.relative_to(case_dir).as_posix()
        strip = strip_for(p)
        clips.append(
            {
                "path": p,
                "rel": rel,
                "strip": strip,
                "sha": sha256(p)[:16],
                "size_mb": p.stat().st_size / 1e6,
                "dur": probe_duration(p),
                "mtime": datetime.fromtimestamp(p.stat().st_mtime).strftime("%Y-%m-%d %H:%M"),
            }
        )

    # flag byte-identical duplicates (same sha256) — e.g. a clip copied into
    # an "incident" subfolder; they are the same evidence, not two items.
    seen_sha: dict[str, str] = {}
    for c in clips:
        first = seen_sha.get(c["sha"])
        if first is None:
            seen_sha[c["sha"]] = c["rel"]
        else:
            c["dup_of"] = first

    if not clips:
        print("error: no video clips found", file=sys.stderr)
        return 1

    out = args.out or (case_dir / "VIDEO-INDEX.pdf")
    title = args.title or f"Video Evidence Index — {case_dir.name}"
    build_pdf(clips, case_dir, out, title, args.per_page)

    # companion markdown index (greppable, git-friendly)
    md = case_dir / "VIDEO-INDEX.md"
    with open(md, "w", encoding="utf-8") as f:
        f.write(f"# {title}\n\n| File | SHA-256 (16) | MB | Dur | Strip |\n")
        f.write("|---|---|---|---|---|\n")
        for c in clips:
            dup = f" ⚠️ dup of `{c['dup_of']}`" if c.get("dup_of") else ""
            f.write(
                f"| `{c['rel']}`{dup} | `{c['sha']}` | {c['size_mb']:.1f} "
                f"| {fmt_dur(c['dur'])} | "
                f"{'yes' if c['strip'] else 'no'} |\n"
            )

    print(f"pdf: {out}")
    print(f"md:  {md}")
    print(f"clips: {len(clips)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
